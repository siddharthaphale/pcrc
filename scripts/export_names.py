"""Generate shell method constants from pcrc.registry; --check detects drift."""

from __future__ import annotations

import argparse
from pathlib import Path

from pcrc.registry import Method


def render() -> dict[str, str]:
    shell = ["# Generated by scripts/export_names.py; edit src/pcrc/registry.py."]
    for method in Method:
        shell.append(f"PCRC_METHOD_{method.name}='{method}'")
    return {"scripts/method_names.sh": "\n".join(shell) + "\n"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for name, content in render().items():
        path = root / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.error("Regenerate stale name references: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
